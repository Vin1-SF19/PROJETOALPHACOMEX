import { it, expect, vi } from 'vitest';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { createHash, randomUUID } from 'node:crypto';
import fixture from './fixtures/consumer-v1.json';
import { identitySchema, profileSchema, notificacaoSchema, loginSchema, observationSchema, operations, statusLeitura } from '../../contracts/portal-api/v1';
import { createPortalClient, readBounded, safeStreamHeaders } from '../../contracts/portal-api/sdk.server';
const config = { origin: 'http://localhost:4391', environment: 'local' as const, appId: 'painelclientes' as const, keyId: 'test-app', key: 'AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA' };
it('provider retains frozen consumer baseline and consumer strips additive fields recursively', () => {
    expect(identitySchema.parse({ ...fixture.identity, newOptional: 'extra' })).toEqual(fixture.identity);
    expect(profileSchema.parse(fixture.profile)).toEqual(fixture.profile);
    expect(notificacaoSchema.parse({ ...fixture.notification, crmInternal: 'private' })).toEqual(fixture.notification);
    expect(loginSchema.safeParse({ email: 'test@example.invalid', senha: 'test', userId: 'other' }).success).toBe(false);
    expect(observationSchema.safeParse({ observacao: null, mutationId: randomUUID(), expectedRevision: 0, patch: { status: 'OK' } }).success).toBe(false);
    expect(statusLeitura).toHaveLength(11);
    expect(operations).toHaveLength(24);
    expect(operations.filter(o => o.authMode === 'A').map(o => o.id)).toEqual(['login', 'recovery', 'reset']);
});
it('generated bytes/manifest reproduce deterministically with no schema/hash handshake', () => {
    execFileSync(process.execPath, ['scripts/portal-api/generate-contract.mjs', '--check']);
    const manifest = JSON.parse(readFileSync('artifacts/portal-api/v1/manifest.json', 'utf8'));
    for (const file of ['v1.ts', 'sdk.server.ts'])
        expect(createHash('sha256').update(readFileSync('artifacts/portal-api/v1/' + file)).digest('hex')).toBe(manifest.files[file]);
    expect(manifest.major).toBe(1);
    expect(manifest).not.toHaveProperty('schemaHash');
    expect(manifest).not.toHaveProperty('timestamp');
});
it('SDK uses explicit principal, fixed app headers and no cookies, accepting major1 minor additions', async () => {
    const fetcher = vi.fn(async (_url: URL | RequestInfo, init?: RequestInit) => {
        expect(init?.redirect).toBe('manual');
        expect(init?.cache).toBe('no-store');
        const h = new Headers(init?.headers);
        expect(h.get('authorization')).toBe('Bearer opaque');
        expect(h.get('cookie')).toBeNull();
        expect(h.get('x-portal-app-key')).toBe(config.key);
        return new Response(JSON.stringify({ ok: true, data: { ...fixture.profile, future: 'accepted' }, requestId: randomUUID(), futureEnvelope: 'accepted' }), { headers: { 'Content-Type': 'application/json', 'X-Portal-Contract-Version': '1.9.0' } });
    });
    const client = createPortalClient({ ...config, fetch: fetcher });
    const r = await client.call('profile', { token: 'opaque' });
    expect(r.ok && r.data).toEqual(fixture.profile);
    expect(fetcher).toHaveBeenCalledOnce();
    await expect(client.call('profile')).rejects.toMatchObject({ status: 401 });
    expect(fetcher).toHaveBeenCalledOnce();
});
it.each([302, 307])('SDK denies redirect %i without following Location', async (status) => {
    const fetcher = vi.fn(async () => new Response(null, { status, headers: { Location: 'https://attacker.invalid' } }));
    const client = createPortalClient({ ...config, fetch: fetcher });
    await expect(client.call('me', { token: 'opaque' })).rejects.toMatchObject({ status: 502 });
    expect(fetcher).toHaveBeenCalledOnce();
});
it('bounded read cancels oversized stream without Content-Length', async () => {
    const cancel = vi.fn();
    const stream = new ReadableStream<Uint8Array>({ pull(c) { c.enqueue(new Uint8Array(4096)); }, cancel });
    await expect(readBounded(stream, 8192)).rejects.toMatchObject({ status: 413 });
    expect(cancel).toHaveBeenCalledOnce();
});
it('SDK bounds errors as well as successes and excludes upstream secrets from binary headers', async () => {
    const client = createPortalClient({ ...config, fetch: async () => new Response('x'.repeat(2097153), { status: 503, headers: { 'Content-Type': 'application/json', 'X-Portal-Contract-Version': '1.0.0' } }) });
    await expect(client.call('me', { token: 'opaque' })).rejects.toMatchObject({ status: 413 });
    const h = safeStreamHeaders(new Response(null, { headers: { 'Content-Type': 'image/png', 'Set-Cookie': 'secret', 'Authorization': 'Bearer secret', 'X-Portal-App-Key': 'secret', Location: 'https://bad.invalid', 'X-Request-Id': randomUUID() } }));
    expect([...h.keys()].sort()).toEqual(['cache-control', 'content-type', 'x-content-type-options', 'x-request-id']);
});
it.each(['https://user:pass@example.invalid', 'https://example.invalid/path', 'http://example.invalid'])('fixed origin rejects %s', origin => expect(() => createPortalClient({ ...config, origin })).toThrow());
it('SDK cancels upload source when principal is absent and normalizes broken JSON transport', async () => {
    vi.useFakeTimers();
    try {
        const cancel = vi.fn();
        const client = createPortalClient({ ...config, fetch: vi.fn() });
        await expect(client.uploadAvatar(new ReadableStream<Uint8Array>({ cancel }), 'image/png', { query: { filename: 'a.png' } })).rejects.toMatchObject({ status: 401 });
        expect(cancel).toHaveBeenCalledOnce();
        expect(vi.getTimerCount()).toBe(0);
    }
    finally {
        vi.useRealTimers();
    }
    const broken = createPortalClient({ ...config, fetch: async () => new Response(new ReadableStream<Uint8Array>({ start(c) { c.error(new Error('transport broken')); } }), { headers: { 'Content-Type': 'application/json', 'X-Portal-Contract-Version': '1.0.0' } }) });
    await expect(broken.call('me', { token: 'opaque' })).rejects.toMatchObject({ status: 502, code: 'RETRYABLE' });
});
